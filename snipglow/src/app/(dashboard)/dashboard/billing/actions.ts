/**
 * Get the active membership for a customer (if any).
 * Returns the membership with its discount_pct if active.
 */
export async function getCustomerActiveMembership(
  customerId: string
): Promise<{ membership: Membership; customerMembership: CustomerMembership } | null> {
  const supabase = await createClient();

  const today = new Date().toISOString().split('T')[0];

  const { data } = await supabase
    .from('customer_memberships')
    .select('*, memberships(*)')
    .eq('customer_id', customerId)
    .eq('status', 'active')
    .gte('end_date', today)
    .order('end_date', { ascending: false })
    .limit(1)
    .single();

  if (!data) return null;

  return {
    customerMembership: {
      id: data.id,
      customer_id: data.customer_id,
      membership_id: data.membership_id,
      tenant_id: data.tenant_id,
      branch_id: data.branch_id ?? '',
      start_date: data.start_date,
      end_date: data.end_date,
      status: data.status as MembershipStatus,
      created_at: data.created_at ?? '',
    },
    membership: data.memberships as unknown as Membership,
  };
}

/**
 * Create an invoice with line items.
 * Applies membership discount automatically if customer has active membership.
 * Calculates GST if provided.
 * The invoice_number is auto-generated by a database trigger.
 */
export async function createInvoice(
  input: CreateInvoiceInput
): Promise<ActionResult<Invoice>> {
  const supabase = await createClient();

  const { data: { user } } = await supabase.auth.getUser();
  if (!user) return { success: false, error: 'Not authenticated' };

  const tenantId = user.user_metadata?.tenant_id;
  const branchId = user.user_metadata?.branch_id;
  if (!tenantId || !branchId) {
    return { success: false, error: 'No tenant or branch context found.' };
  }

  if (!input.customer_id) {
    return { success: false, error: 'Customer is required.' };
  }
  if (!input.items || input.items.length === 0) {
    return { success: false, error: 'At least one service item is required.' };
  }
  if (!input.payment_method) {
    return { success: false, error: 'Payment method is required.' };
  }

  // Calculate totals
  const discountPct = input.discount_pct ?? 0;
  const gstRate = input.gst_rate ?? 0;

  const totals = calculateInvoiceTotal({
    lineItems: input.items.map((item) => ({
      price: item.unit_price,
      quantity: item.quantity,
    })),
    membershipDiscountPct: discountPct,
    gstRate: gstRate,
  });

  // Insert invoice (invoice_number is auto-generated by DB trigger)
  const { data: invoice, error: invoiceError } = await supabase
    .from('invoices')
    .insert({
      tenant_id: tenantId,
      branch_id: branchId,
      customer_id: input.customer_id,
      appointment_id: input.appointment_id ?? null,
      invoice_number: '', // trigger will generate
      subtotal: totals.subtotal,
      discount_amount: totals.discountAmount,
      discount_pct: discountPct,
      gst_amount: totals.gstAmount,
      gst_rate: gstRate,
      total: totals.total,
      payment_method: input.payment_method,
      payment_status: 'paid',
      delivery_status: 'pending',
    })
    .select()
    .single();

  if (invoiceError) {
    console.error('Invoice creation error:', invoiceError);
    return { success: false, error: 'Failed to create invoice. Please try again.' };
  }

  // Insert invoice items
  const invoiceItems = input.items.map((item) => ({
    invoice_id: invoice.id,
    service_id: item.service_id,
    service_name: item.service_name,
    unit_price: item.unit_price,
    quantity: item.quantity,
    line_total: item.unit_price * item.quantity,
  }));

  const { error: itemsError } = await supabase
    .from('invoice_items')
    .insert(invoiceItems);

  if (itemsError) {
    console.error('Invoice items creation error:', itemsError);
    // Invoice was created but items failed — still return the invoice
    return { success: true, data: invoice as Invoice };
  }

  // Send bill receipt to customer via WhatsApp + feedback request
  await sendBillReceiptWhatsApp(
    tenantId,
    input.customer_id,
    input.items,
    invoice.invoice_number,
    totals.subtotal,
    discountPct,
    totals.discountAmount,
    totals.total,
    input.payment_method
  );

  revalidatePath('/dashboard/billing');
  return { success: true, data: invoice as Invoice };
}

/**
 * Send an invoice via WhatsApp (placeholder — calls Edge Function).
 */
export async function sendInvoiceWhatsApp(invoiceId: string): Promise<ActionResult<void>> {
  const supabase = await createClient();

  const { data: { user } } = await supabase.auth.getUser();
  if (!user) return { success: false, error: 'Not authenticated' };

  // Call the send-invoice Edge Function
  const { error } = await supabase.functions.invoke('send-invoice', {
    body: { invoice_id: invoiceId },
  });

  if (error) {
    return { success: false, error: 'Failed to send invoice via WhatsApp. Please try again.' };
  }

  revalidatePath('/dashboard/billing');
  return { success: true, data: undefined };
}

/**
 * Update an invoice's payment method and payment status.
 */
export async function updateInvoicePayment(
  invoiceId: string,
  updates: { payment_method: 'cash' | 'upi' | 'card'; payment_status: 'paid' | 'partial' | 'pending' }
): Promise<ActionResult<void>> {
  const supabase = await createClient();

  const { data: { user } } = await supabase.auth.getUser();
  if (!user) return { success: false, error: 'Not authenticated' };

  const { error } = await supabase
    .from('invoices')
    .update({
      payment_method: updates.payment_method,
      payment_status: updates.payment_status,
    })
    .eq('id', invoiceId);

  if (error) {
    return { success: false, error: 'Failed to update invoice. Please try again.' };
  }

  revalidatePath('/dashboard/billing');
  return { success: true, data: undefined };
}

/**
 * Get the tenant's GST and discount settings.
 */
export async function getTenantGstSettings(): Promise<{ gst_enabled: boolean; gst_rate: number; gst_number: string | null; discount_enabled: boolean; discount_value: number }> {
  const supabase = await createClient();

  const { data: { user } } = await supabase.auth.getUser();
  if (!user) return { gst_enabled: false, gst_rate: 0, gst_number: null, discount_enabled: false, discount_value: 0 };

  const tenantId = user.user_metadata?.tenant_id;
  if (!tenantId) return { gst_enabled: false, gst_rate: 0, gst_number: null, discount_enabled: false, discount_value: 0 };

  const { data: tenant } = await supabase
    .from('tenants')
    .select('settings')
    .eq('id', tenantId)
    .single();

  if (!tenant) return { gst_enabled: false, gst_rate: 0, gst_number: null, discount_enabled: false, discount_value: 0 };

  const settings = (tenant.settings as Record<string, unknown>) ?? {};
  const gstEnabled = (settings.gst_enabled as boolean) ?? false;
  // India: hair salons & beauty spas attract 5% GST on services. Default to 5%
  // when GST is enabled but no explicit rate has been stored.
  const storedRate = (settings.gst_rate as number) ?? 0;
  return {
    gst_enabled: gstEnabled,
    gst_rate: gstEnabled ? (storedRate > 0 ? storedRate : 5) : 0,
    gst_number: (settings.gst_number as string) ?? null,
    discount_enabled: (settings.discount_enabled as boolean) ?? false,
    discount_value: (settings.discount_value as number) ?? 0,
  };
}

