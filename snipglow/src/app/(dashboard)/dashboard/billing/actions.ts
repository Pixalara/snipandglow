/**
 * Get the active membership for a customer (if any).
 * Returns the membership with its discount_pct if active.
 */
export async function getCustomerActiveMembership(
  customerId: string
): Promise<{ membership: Membership; customerMembership: CustomerMembership } | null> {
  const supabase = await createClient();

  const today = new Date().toISOString().split('T')[0];

  const { data } = await supabase
    .from('customer_memberships')
    .select('*, memberships(*)')
    .eq('customer_id', customerId)
    .eq('status', 'active')
    .gte('end_date', today)
    .order('end_date', { ascending: false })
    .limit(1)
    .single();

  if (!data) return null;

  return {
    customerMembership: {
      id: data.id,
      customer_id: data.customer_id,
      membership_id: data.membership_id,
      tenant_id: data.tenant_id,
      branch_id: data.branch_id ?? '',
      start_date: data.start_date,
      end_date: data.end_date,
      status: data.status as MembershipStatus,
      created_at: data.created_at ?? '',
    },
    membership: data.memberships as unknown as Membership,
  };
}

/**
 * Active products available to sell on a bill (with current stock).
 * RLS scopes to the current tenant. Used by the new-bill screen.
 */
export interface BillableProduct {
  id: string;
  name: string;
  selling_price: number;
  stock_quantity: number;
  unit: string;
}

export async function getBillableProducts(): Promise<BillableProduct[]> {
  const supabase = await createClient();
  const { data: { user } } = await supabase.auth.getUser();
  if (!user) return [];

  const { data, error } = await (supabase as any)
    .from('products')
    .select('id, name, selling_price, stock_quantity, unit')
    .eq('is_active', true)
    .order('name', { ascending: true });

  if (error) {
    console.error('getBillableProducts error:', error);
    return [];
  }
  return (data ?? []) as BillableProduct[];
}

/**
 * Create an invoice with line items.
 * Applies membership discount automatically if customer has active membership.
 * Calculates GST if provided.
 * The invoice_number is auto-generated by a database trigger.
 */
export async function createInvoice(
  input: CreateInvoiceInput
): Promise<ActionResult<Invoice>> {
  const supabase = await createClient();

  const { data: { user } } = await supabase.auth.getUser();
  if (!user) return { success: false, error: 'Not authenticated' };

  const tenantId = user.user_metadata?.tenant_id;
  const branchId = user.user_metadata?.branch_id;
  if (!tenantId || !branchId) {
    return { success: false, error: 'No tenant or branch context found.' };
  }

  if (!input.customer_id) {
    return { success: false, error: 'Customer is required.' };
  }
  if (!input.items || input.items.length === 0) {
    return { success: false, error: 'At least one item is required.' };
  }
  if (!input.payment_method) {
    return { success: false, error: 'Payment method is required.' };
  }

  // Calculate totals (per-item discounts; bill-level discount_pct kept as a
  // fallback applied to any line that doesn't specify its own).
  const fallbackPct = input.discount_pct ?? 0;
  const gstRate = input.gst_rate ?? 0;

  // --- Product stock pre-check -------------------------------------------
  // Aggregate quantities per product across all product line items, then make
  // sure there is enough stock BEFORE creating the invoice. Block (with a clear
  // message) rather than overselling.
  const qtyByProduct = new Map<string, number>();
  for (const it of input.items) {
    if (it.item_type === 'product' && it.product_id) {
      qtyByProduct.set(it.product_id, (qtyByProduct.get(it.product_id) ?? 0) + it.quantity);
    }
  }
  let productRows: { id: string; name: string; stock_quantity: number; branch_id: string | null; is_active: boolean }[] = [];
  if (qtyByProduct.size > 0) {
    const { data: prods, error: prodErr } = await (supabase as any)
      .from('products')
      .select('id, name, stock_quantity, branch_id, is_active')
      .in('id', Array.from(qtyByProduct.keys()));
    if (prodErr) {
      console.error('Invoice product lookup error:', prodErr);
      return { success: false, error: 'Failed to check product stock. Please try again.' };
    }
    productRows = (prods ?? []) as typeof productRows;
    for (const [pid, qty] of qtyByProduct) {
      const p = productRows.find((r) => r.id === pid);
      if (!p) return { success: false, error: 'One of the selected products was not found.' };
      if (!p.is_active) return { success: false, error: `${p.name} is inactive and cannot be sold.` };
      if (Number(p.stock_quantity) < qty) {
        return { success: false, error: `Not enough stock for ${p.name}. Only ${p.stock_quantity} left in stock.` };
      }
    }
  }

  const totals = calculatePerItemInvoiceTotal({
    lineItems: input.items.map((item) => ({
      price: item.unit_price,
      quantity: item.quantity,
      discountPct: item.discount_pct ?? fallbackPct,
    })),
    gstRate: gstRate,
  });
  const billDiscountPct = blendedDiscountPct(totals.subtotal, totals.discountAmount);

  // --- Wallet pre-check ---------------------------------------------------
  // Re-read the balance server-side (never trust the client). The authoritative
  // debit happens atomically AFTER the invoice is created (wallet_debit_for_invoice).
  let walletUse = 0;
  if (input.wallet_amount && input.wallet_amount > 0) {
    const { data: walletRow } = await (supabase as any)
      .from('customer_wallets')
      .select('balance')
      .eq('customer_id', input.customer_id)
      .maybeSingle();
    const balance = walletRow ? Number(walletRow.balance) : 0;
    if (input.wallet_amount > balance) {
      return { success: false, error: `Insufficient wallet balance. Available: ₹${balance}.` };
    }
    walletUse = clampWalletUse(input.wallet_amount, totals.total, balance);
  }

  // Insert invoice (invoice_number is auto-generated by DB trigger)
  const { data: invoice, error: invoiceError } = await supabase
    .from('invoices')
    .insert({
      tenant_id: tenantId,
      branch_id: branchId,
      customer_id: input.customer_id,
      appointment_id: input.appointment_id ?? null,
      invoice_number: '', // trigger will generate
      subtotal: totals.subtotal,
      discount_amount: totals.discountAmount,
      discount_pct: billDiscountPct,
      gst_amount: totals.gstAmount,
      gst_rate: gstRate,
      total: totals.total,
      payment_method: input.payment_method,
      payment_status: 'paid',
      delivery_status: 'pending',
    })
    .select()
    .single();

  if (invoiceError) {
    console.error('Invoice creation error:', invoiceError);
    return { success: false, error: 'Failed to create invoice. Please try again.' };
  }

  // Insert invoice items
  const invoiceItems = input.items.map((item, idx) => {
    const line = totals.lines[idx];
    return {
      invoice_id: invoice.id,
      service_id: item.item_type === 'product' ? null : item.service_id,
      product_id: item.item_type === 'product' ? (item.product_id ?? null) : null,
      item_type: item.item_type ?? 'service',
      service_name: item.service_name,
      unit_price: item.unit_price,
      quantity: item.quantity,
      discount_pct: line.discountPct,
      discount_amount: line.discountAmount,
      line_total: line.net,
    };
  });

  const { error: itemsError } = await supabase
    .from('invoice_items')
    .insert(invoiceItems as any);

  if (itemsError) {
    console.error('Invoice items creation error:', itemsError);
    // Invoice was created but items failed — still return the invoice
    return { success: true, data: invoice as Invoice };
  }

  // --- Apply wallet payment (atomic, server-validated) -------------------
  // Runs only AFTER the invoice + items exist. The DB function row-locks the
  // wallet and refuses to overdraw. If it fails, we delete the just-created
  // invoice so the wallet balance and the bill never disagree.
  if (walletUse > 0) {
    const { error: debitErr } = await (supabase as any).rpc('wallet_debit_for_invoice', {
      p_invoice_id: invoice.id,
      p_amount: walletUse,
    });
    if (debitErr) {
      console.error('Wallet debit error:', debitErr);
      try {
        const admin = createAdminClient();
        await (admin.from('invoices' as any).delete().eq('id', invoice.id) as any);
      } catch (rollbackErr) {
        console.error('Wallet debit rollback (invoice delete) failed:', rollbackErr);
      }
      const msg = String(debitErr.message || '');
      return {
        success: false,
        error: msg.includes('INSUFFICIENT_WALLET_BALANCE')
          ? 'Insufficient wallet balance. Please refresh and try again.'
          : 'Failed to apply wallet payment. Please try again.',
      };
    }
  }

  // --- Decrement product stock + record 'sale' movements -----------------
  // Runs only when the invoice has product line items. Best-effort: a failure
  // here is logged but does not fail the (already created) invoice.
  if (qtyByProduct.size > 0) {
    const { data: employee } = await supabase
      .from('employees')
      .select('id')
      .eq('auth_user_id', user.id)
      .maybeSingle();

    for (const [pid, qty] of qtyByProduct) {
      const p = productRows.find((r) => r.id === pid);
      if (!p) continue;
      const newStock = Math.max(0, Number(p.stock_quantity) - qty);

      const { error: stockErr } = await (supabase as any)
        .from('products')
        .update({ stock_quantity: newStock, updated_at: new Date().toISOString() })
        .eq('id', pid);
      if (stockErr) {
        console.error('Invoice stock decrement error:', stockErr);
        continue;
      }

      const { error: moveErr } = await (supabase as any).from('inventory_movements').insert({
        tenant_id: tenantId,
        branch_id: p.branch_id ?? branchId,
        product_id: pid,
        movement_type: 'sale',
        quantity: -qty,
        note: `Sold on invoice ${invoice.invoice_number}`,
        reference_type: 'invoice',
        reference_id: invoice.id,
        created_by: employee?.id ?? null,
      });
      if (moveErr) {
        console.error('Invoice sale movement log error:', moveErr);
      }
    }
    revalidatePath('/dashboard/inventory');
  }

  // Send bill receipt to customer via WhatsApp + feedback request
  await sendBillReceiptWhatsApp(
    tenantId,
    input.customer_id,
    input.items,
    invoice.invoice_number,
    totals.subtotal,
    billDiscountPct,
    totals.discountAmount,
    totals.total,
    input.payment_method,
    walletUse
  );

  revalidatePath('/dashboard/billing');
  if (walletUse > 0) {
    revalidatePath(`/dashboard/customers/${input.customer_id}`);
  }
  return { success: true, data: invoice as Invoice };
}

/**
 * Send an invoice via WhatsApp (placeholder — calls Edge Function).
 */
export async function sendInvoiceWhatsApp(invoiceId: string): Promise<ActionResult<void>> {
  const supabase = await createClient();

  const { data: { user } } = await supabase.auth.getUser();
  if (!user) return { success: false, error: 'Not authenticated' };

  // Call the send-invoice Edge Function
  const { error } = await supabase.functions.invoke('send-invoice', {
    body: { invoice_id: invoiceId },
  });

  if (error) {
    return { success: false, error: 'Failed to send invoice via WhatsApp. Please try again.' };
  }

  revalidatePath('/dashboard/billing');
  return { success: true, data: undefined };
}

/**
 * Update an invoice's payment method and payment status.
 */
export async function updateInvoicePayment(
  invoiceId: string,
  updates: { payment_method: 'cash' | 'upi' | 'card'; payment_status: 'paid' | 'partial' | 'pending' }
): Promise<ActionResult<void>> {
  const supabase = await createClient();

  const { data: { user } } = await supabase.auth.getUser();
  if (!user) return { success: false, error: 'Not authenticated' };

  const { error } = await supabase
    .from('invoices')
    .update({
      payment_method: updates.payment_method,
      payment_status: updates.payment_status,
    })
    .eq('id', invoiceId);

  if (error) {
    return { success: false, error: 'Failed to update invoice. Please try again.' };
  }

  revalidatePath('/dashboard/billing');
  return { success: true, data: undefined };
}

/**
 * Get the tenant's GST and discount settings.
 */
export async function getTenantGstSettings(): Promise<{ gst_enabled: boolean; gst_rate: number; gst_number: string | null; discount_enabled: boolean; discount_value: number }> {
  const supabase = await createClient();

  const { data: { user } } = await supabase.auth.getUser();
  if (!user) return { gst_enabled: false, gst_rate: 0, gst_number: null, discount_enabled: false, discount_value: 0 };

  const tenantId = user.user_metadata?.tenant_id;
  if (!tenantId) return { gst_enabled: false, gst_rate: 0, gst_number: null, discount_enabled: false, discount_value: 0 };

  const { data: tenant } = await supabase
    .from('tenants')
    .select('settings')
    .eq('id', tenantId)
    .single();

  if (!tenant) return { gst_enabled: false, gst_rate: 0, gst_number: null, discount_enabled: false, discount_value: 0 };

  const settings = (tenant.settings as Record<string, unknown>) ?? {};
  const gstEnabled = (settings.gst_enabled as boolean) ?? false;
  // India: hair salons & beauty spas attract 5% GST on services. Default to 5%
  // when GST is enabled but no explicit rate has been stored.
  const storedRate = (settings.gst_rate as number) ?? 0;
  return {
    gst_enabled: gstEnabled,
    gst_rate: gstEnabled ? (storedRate > 0 ? storedRate : 5) : 0,
    gst_number: (settings.gst_number as string) ?? null,
    discount_enabled: (settings.discount_enabled as boolean) ?? false,
    discount_value: (settings.discount_value as number) ?? 0,
  };
}

