export interface InvoiceDocumentItem {
  service_name: string;
  unit_price: number;
  quantity: number;
  /** Per-line discount % (0 when none). */
  discount_pct: number;
  /** Per-line discount amount (0 when none). */
  discount_amount: number;
  /** Net line total (after the line discount). */
  line_total: number;
}

export interface InvoiceDocument {
  invoice_number: string;
  created_at: string;
  payment_method: string;
  payment_status: string;
  subtotal: number;
  discount_pct: number;
  discount_amount: number;
  gst_rate: number;
  gst_amount: number;
  total: number;
  items: InvoiceDocumentItem[];
  customer: { name: string; phone: string | null; email: string | null };
  salon: {
    name: string;
    legal_name: string | null;
    trade_name: string | null;
    address: string | null;
    phone: string | null;
    email: string | null;
    gst_number: string | null;
  };
  /** 'service' (default) or 'wallet_recharge'. */
  invoice_type?: 'service' | 'wallet_recharge';
  /** Portion of this bill paid from the wallet (service invoices). */
  wallet_amount?: number;
  /** Customer's wallet balance after this invoice (null if unknown). */
  wallet_balance_after?: number | null;
}

/**
 * Fetch the full invoice document (invoice + items + customer + salon)
 * for rendering a premium printable/downloadable receipt.
 * RLS scopes the invoice to the current tenant.
 */
export async function getInvoiceDocument(
  invoiceId: string
): Promise<ActionResult<InvoiceDocument>> {
  const supabase = await createClient();

  const { data: { user } } = await supabase.auth.getUser();
  if (!user) return { success: false, error: 'Not authenticated' };

  const tenantId = user.user_metadata?.tenant_id as string | undefined;
  if (!tenantId) return { success: false, error: 'No tenant context found.' };

  // Fetch invoice (RLS-scoped)
  const { data: invoice, error: invErr } = await (supabase as any)
    .from('invoices')
    .select('id, invoice_number, created_at, payment_method, payment_status, subtotal, discount_pct, discount_amount, gst_rate, gst_amount, total, customer_id, branch_id, invoice_type, wallet_amount')
    .eq('id', invoiceId)
    .single();

  if (invErr || !invoice) {
    return { success: false, error: 'Invoice not found.' };
  }

  // Fetch line items, customer, tenant, branch, and wallet balance in parallel
  const [itemsRes, customerRes, tenantRes, branchRes, walletRes] = await Promise.all([
    supabase
      .from('invoice_items')
      .select('service_name, unit_price, quantity, discount_pct, discount_amount, line_total')
      .eq('invoice_id', invoiceId),
    invoice.customer_id
      ? supabase.from('customers').select('name, phone, email').eq('id', invoice.customer_id).single()
      : Promise.resolve({ data: null }),
    supabase.from('tenants').select('name, phone, settings').eq('id', tenantId).single(),
    invoice.branch_id
      ? supabase.from('branches').select('name, address, phone').eq('id', invoice.branch_id).single()
      : Promise.resolve({ data: null }),
    invoice.customer_id
      ? (supabase as any).from('customer_wallets').select('balance').eq('customer_id', invoice.customer_id).maybeSingle()
      : Promise.resolve({ data: null }),
  ]);

  const settings = ((tenantRes.data?.settings as Record<string, unknown>) ?? {});
  const customer = (customerRes.data as { name: string; phone: string | null; email: string | null } | null);
  const branch = (branchRes.data as { name: string; address: string | null; phone: string | null } | null);
  const walletAmount = Number((invoice as any).wallet_amount ?? 0);
  const invoiceType = (((invoice as any).invoice_type as 'service' | 'wallet_recharge') ?? 'service');
  const walletBalanceAfter = (walletRes as any)?.data ? Number((walletRes as any).data.balance) : null;

  const doc: InvoiceDocument = {
    invoice_number: invoice.invoice_number,
    created_at: invoice.created_at ?? new Date().toISOString(),
    // For a fully-wallet-paid service bill, present the method as "Wallet".
    payment_method:
      invoiceType === 'service' && walletAmount > 0 && walletAmount >= (invoice.total ?? 0)
        ? 'wallet'
        : (invoice.payment_method ?? 'cash'),
    payment_status: invoice.payment_status ?? 'paid',
    subtotal: invoice.subtotal ?? 0,
    discount_pct: invoice.discount_pct ?? 0,
    discount_amount: invoice.discount_amount ?? 0,
    gst_rate: invoice.gst_rate ?? 0,
    gst_amount: invoice.gst_amount ?? 0,
    total: invoice.total ?? 0,
    invoice_type: invoiceType,
    wallet_amount: walletAmount,
    wallet_balance_after: walletBalanceAfter,
    items: (itemsRes.data ?? []).map((it: any) => ({
      service_name: it.service_name,
      unit_price: it.unit_price,
      quantity: it.quantity,
      discount_pct: it.discount_pct ?? 0,
      discount_amount: it.discount_amount ?? 0,
      line_total: it.line_total ?? it.unit_price * it.quantity,
    })),
    customer: {
      name: customer?.name ?? '—',
      phone: customer?.phone ?? null,
      email: customer?.email ?? null,
    },
    salon: {
      name: (tenantRes.data?.name as string) ?? 'Salon',
      legal_name: (settings.legal_name as string) ?? null,
      trade_name: (settings.trade_name as string) ?? null,
      address: branch?.address ?? null,
      phone: branch?.phone ?? (tenantRes.data?.phone as string) ?? null,
      email: (settings.email as string) ?? null,
      gst_number: (settings.gst_number as string) ?? null,
    },
  };

  return { success: true, data: doc };
}
